// Generates src/icons/iconoir.ts: every Iconoir icon as its own named export,
// pre-converted to morphicons data. Unused exports are tree-shaken by the bundler,
// so only the icons you import reach the browser.
//
// Runs automatically before `dev` and `build` (see package.json). Usage:
//   import { Mail, Xmark, ICONOIR_STROKE_WIDTH } from "@/icons/iconoir";
//   <MorphIcon icon={open ? Xmark : Mail} strokeWidth={ICONOIR_STROKE_WIDTH} />

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { icons } from "@iconify-json/iconoir";
import { svgToIcon } from "morphicons/adapters";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = resolve(root, "src/icons/iconoir.ts");

// "arrow-up-circle" -> "ArrowUpCircle"
const toExportName = (name) => {
  const pascal = name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
  return /^[0-9]/.test(pascal) ? `Icon${pascal}` : pascal;
};

const lines = [];
const seen = new Map(); // export name -> icon name, to catch collisions
const skipped = [];

const add = (iconName, line) => {
  const exportName = toExportName(iconName);
  if (seen.has(exportName)) {
    throw new Error(`Export name collision: "${iconName}" and "${seen.get(exportName)}" -> ${exportName}`);
  }
  seen.set(exportName, iconName);
  lines.push(line(exportName));
};

for (const [name, { body }] of Object.entries(icons.icons)) {
  let data;
  try {
    data = svgToIcon(body);
  } catch (err) {
    skipped.push(`${name} (${err.message})`);
    continue;
  }
  add(name, (exp) => `export const ${exp}: IconNode = ${JSON.stringify(data)};`);
}

// Aliases point at another icon. Ones with transforms (rotate/flip) are skipped.
for (const [name, alias] of Object.entries(icons.aliases ?? {})) {
  const hasTransform = Object.keys(alias).some((k) => k !== "parent");
  if (hasTransform || !seen.has(toExportName(alias.parent))) {
    skipped.push(`${name} (alias)`);
    continue;
  }
  add(name, (exp) => `export const ${exp} = ${toExportName(alias.parent)};`);
}

const header = `// AUTO-GENERATED by scripts/build-icons.mjs from @iconify-json/iconoir. Do not edit.
import type { IconNode } from "morphicons";

/** Iconoir is drawn at 1.5; MorphIcon defaults to 2. */
export const ICONOIR_STROKE_WIDTH = 1.5;
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, `${header}\n${lines.join("\n")}\n`);

console.log(`iconoir: wrote ${lines.length} icons to src/icons/iconoir.ts`);
if (skipped.length) console.log(`iconoir: skipped ${skipped.length}: ${skipped.join(", ")}`);
